import { describe, expect, it } from "vitest";
import fixtures from "./__fixtures__/protocol.json";
import { cleanText, validateName, type ServerMsg } from "./protocol";
import { Model } from "./game/model";

const server = fixtures.server as unknown as ServerMsg[];

describe("protocol fixtures generated by the Rust server types", () => {
  it("covers every server message tag the client understands", () => {
    const tags = new Set(server.map((m) => m.t));
    for (const t of ["welcome", "error", "characters", "enter_world", "snapshot", "sheet", "events", "chat", "party", "dialogue", "pong", "kicked"]) {
      expect(tags.has(t as ServerMsg["t"])).toBe(true);
    }
  });

  it("drives the client model end to end", () => {
    const enter = server.find((m) => m.t === "enter_world");
    const snap = server.find((m) => m.t === "snapshot");
    const events = server.find((m) => m.t === "events");
    if (enter?.t !== "enter_world" || snap?.t !== "snapshot" || events?.t !== "events") throw new Error("fixtures incomplete");
    const m = new Model(enter.you, enter.map, enter.sheet);
    expect(m.doorClosed(2, 1)).toBe(true);
    m.sheet = { ...m.sheet, open_doors: ["d"] };
    expect(m.doorClosed(2, 1)).toBe(false);
    m.applySnapshot(snap, 1000);
    expect(m.meView?.boss?.vulnerable).toBe(true);
    expect(m.entities.get(7)?.view.look?.hue).toBe(2);
    expect(m.tele[0].t.kind).toBe("shockwave");
    m.applyEvents(events.events);
    expect(m.effects.length).toBeGreaterThan(0);
    expect(m.toasts.length).toBeGreaterThan(0);
    expect(m.banner).not.toBeNull();
  });
});

describe("text safety", () => {
  it("strips control and bidi characters", () => {
    expect(cleanText("a\u001b[31mb‮\u0007c")).toBe("a[31mbc");
  });
  it("validates names like the server", () => {
    expect(validateName("Alice")).toBeNull();
    expect(validateName("2bad")).not.toBeNull();
    expect(validateName("<script>")).not.toBeNull();
    expect(validateName("ab")).not.toBeNull();
  });
});
